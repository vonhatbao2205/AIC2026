"""V-KIS canvas query: the drawing IS the query, as structure — never as a picture.

For V-KIS the operator redraws a clip from memory: labelled object boxes are
dragged onto a 16:9 canvas, given one of the OD palette colours, and marked
required or optional. The frontend therefore already knows every label, colour
and normalized bbox. Rendering that to a PNG and asking an encoder to read the
structure back would only lose it, so the canvas JSON stays the query and is used
two ways:

  1. structured match against the OD index (`object_layout` channel) — each drawn
     object is matched one-to-one with a real detection by Hungarian assignment,
     so two drawn people cannot both match the same detected person;
  2. short English sentences for the PE text encoder, generated by rule (0 ms, no
     hallucination) rather than by a VLM.

Those two channels are the whole canvas pipeline. Rendering the canvas to a
raster for PE-image search is deliberately not implemented: freehand icons sit
far outside the photo distribution PE was trained on, so it would add a noisy
channel to reason about for little recall.

Everything here is pure logic over plain dicts so the scoring can be unit-tested
without Elastic, Milvus or a browser.
"""
